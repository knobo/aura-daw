//! Gate A: the property-test gate (round-2 §7 tests 1, 3, 5) for the
//! transaction channel (Tasks 1-7). Lives as an integration test because the
//! whole surface it exercises (`Session`, `Tx`, `control::op::*`) is already
//! `pub` through `aura_lib::control` — no visibility changes were needed to
//! reach it from here, which is why this suite sits in `tests/` rather than
//! as a `#[cfg(test)]` module inside `src/control/session.rs` (that would
//! have required nothing extra either, but this keeps property-test-only
//! dependencies, like `proptest`, out of the crate's own `#[cfg(test)]`
