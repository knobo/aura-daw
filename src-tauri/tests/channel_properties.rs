//! (in-module) from integration coverage (this directory)).
//!
//! Test helpers here (`fresh_session_3_tracks`, `test_track`, `user_meta`,
//! `set_gain`) are deliberately NOT the private ones in
//! `src/control/session.rs`'s `#[cfg(test)]` module (those are crate-private
